// 8 layers: la capa exterior cubre el 99% del contorno, degradado hacia la punta
const LAYERS = [
  { trailRatio: 0.99, opacity: 0,    strokeWidth: 5, blur: 14 },
  { trailRatio: 0.85, opacity: 0.07, strokeWidth: 5, blur: 12 },
  { trailRatio: 0.70, opacity: 0.11, strokeWidth: 4, blur: 10 },
  { trailRatio: 0.55, opacity: 0.17, strokeWidth: 4, blur: 8  },
  { trailRatio: 0.40, opacity: 0.26, strokeWidth: 3, blur: 6  },
  { trailRatio: 0.27, opacity: 0.40, strokeWidth: 3, blur: 4  },
  { trailRatio: 0.14, opacity: 0.62, strokeWidth: 2, blur: 3  },
  { trailRatio: 0.05, opacity: 0.90, strokeWidth: 2, blur: 2  },
] as const

export function CanariasAnimation({ className }: { className?: string }) {
  const svgRef = useRef<SVGSVGElement>(null)

  useEffect(() => {
    if (!svgRef.current) return

    const measurePaths = svgRef.current.querySelectorAll<SVGPathElement>('[data-ca-measure]')
    const rules: string[] = []

    measurePaths.forEach((path, i) => {
      const total = path.getTotalLength()
      if (!total) return

      const { duration, delay } = ISLANDS[i]

      rules.push(
        `@keyframes ca${i}{from{stroke-dashoffset:0}to{stroke-dashoffset:${total}}}`
      )

      LAYERS.forEach((layer, li) => {
        const trail = total * layer.trailRatio
        const gap   = total - trail
        rules.push(
          `.ca${i}l${li}{stroke-dasharray:${trail} ${gap};animation:ca${i} ${duration}s linear ${delay}s infinite}`
        )
      })
    })

    const styleEl = document.createElement('style')
    styleEl.textContent = rules.join('\n')
    document.head.appendChild(styleEl)

    return () => styleEl.remove()
  }, [])

  return (
    <svg
      ref={svgRef}
      viewBox="0 0 1920 1080"
      className={className}
      aria-hidden="true"
      role="presentation"
    >
      <defs>
        {LAYERS.map((layer, li) => (
          <filter key={li} id={`ca-glow-${li}`} x="-80%" y="-80%" width="260%" height="260%">
            <feGaussianBlur in="SourceGraphic" stdDeviation={layer.blur} result="blur" />
            <feMerge>
              <feMergeNode in="blur" />
              <feMergeNode in="SourceGraphic" />
            </feMerge>
          </filter>
        ))}
      </defs>

      {ISLANDS.map((island, i) => (
        <g key={i}>
          {/* Ghost outline — silueta de referencia */}
          <path
            d={island.d}
            fill="none"
            stroke="white"
            strokeWidth={2}
            strokeOpacity={0.07}
          />

          {/* Path invisible solo para medir la longitud total */}
          <path d={island.d} data-ca-measure="" fill="none" stroke="none" />

          {/* Capas del cometa: halo ancho y tenue → punta corta y brillante */}
          {LAYERS.map((layer, li) => (
            <path
              key={li}
              d={island.d}
              fill="none"
              stroke="white"
              strokeWidth={layer.strokeWidth}
              strokeOpacity={layer.opacity}
              strokeLinecap="round"
              strokeLinejoin="round"
              className={`ca${i}l${li}`}
              filter={`url(#ca-glow-${li})`}
            />
          ))}
        </g>
      ))}
    </svg>
  )
}
